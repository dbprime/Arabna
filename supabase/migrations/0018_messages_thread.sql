-- 0018 — الرسالةُ تصل الطرفين، والمحادثةُ تعرف طرفيها (671)
--
-- ⚠️ العطل، بجملةٍ واحدة: المشتري لا يرى ردَّ البائع. أبداً — لا على
-- جهازه، ولا على غيره، ولا بعد سنة. وليس عطلَ جهازٍ ثانٍ: قِيس الطريقُ
-- كلُّه في 10 سبتمبر 2026 فظهر أنّ العطلَ مطلق. والسوقُ كلُّه مبنيٌّ على
-- أن يتحدّث اثنان.
--
-- والسببُ عمودٌ ناقص: الجدولُ يحمل `listing_id` و`sender_id` ولا ثالثَ
-- يقول لمن. فسياسةُ القراءة تسأل «أأنت الكاتب؟» أو «أأنت صاحبَ
-- الإعلان؟» — وردُّ البائع ليس واحداً منهما بالنسبة للمشتري، فالفرعان
-- يسقطان والصفُّ لا يصل. وPostgREST تجيب قائمةً أقصرَ بحالة 200 بلا
-- خطأ، فلا علامةَ في أيّ مكان.
--
-- ⚠️ ولا يُصلَح بتوسيع السياسة وحدَها. «ومن كتب على هذا الإعلان يقرأ
-- كلَّ ما عليه» سطرٌ واحد — وبمشترِيَين على إعلان، يقرأ الأوّلُ محادثةَ
-- الثاني الخاصّة: اسمَه وسؤالَه وسعرَه الذي عرضه. وتسريبُ محادثةٍ
-- خاصّةٍ بين غريبين أسوأُ من ردٍّ لا يصل. فالبنيةُ تُصحَّح قبل السياسة،
-- لا بدلاً منها.
--
-- ⚠️ ولا `concat` ولا نجمةٌ في الشيفرة: حقلُ محرِّر SQL يُسقِط الحرفين —
-- قاعدةٌ مقيسةٌ مرّتين.

-- ---------------------------------------------------------------
-- 1) مفتاحُ المحادثة
-- ---------------------------------------------------------------
-- `buyer_id` هو الطرفُ الذي ليس صاحبَ الإعلان، أيّاً كان كاتبُ الرسالة:
--     المشتري يكتب  ->  buyer_id هو نفسُه
--     البائعُ يردّ   ->  buyer_id هو المشتري الذي يردّ عليه
--
-- ⚠️ ولماذا مفتاحُ محادثةٍ لا `recipient_id`: البائعُ يحتاج صندوقَه كلَّه
-- (كلَّ محادثات إعلانه) والمشتري يحتاج محادثتَه هو. ومفتاحُ المحادثة
-- يعطي الاثنين بشرطٍ واحد. و`recipient_id` يعطي الأوّلَ بشرطٍ ثانٍ
-- مكرَّرٍ مع `owner_id`، ولا يفصل مشترياً عن مشترٍ أصلاً.
--
-- ⚠️ ويقبل `null` ولا يُفرَض `not null`: الصفوفُ القائمةُ التي كتبها
-- صاحبُ الإعلان لا يُعرَف لمن كانت، ولا يُخترَع لها طرف. تبقى `null`،
-- وتُقرأ لكاتبها ولصاحب الإعلان كما اليوم. وصفٌّ لا يُعرَف طرفُه أفضلُ
-- من صفٍّ نُسب إلى طرفٍ خطأً.
alter table public.messages
  add column if not exists buyer_id uuid references public.profiles(id) on delete cascade;

-- والملءُ الرجعيُّ لما يُعرَف، ولا شيءَ غيره: كاتبٌ ليس صاحبَ الإعلان
-- هو المشتري بالتعريف. ومن كتبها صاحبُ الإعلان تُترَك `null`.
update public.messages m set buyer_id = m.sender_id
 where m.buyer_id is null
   and m.sender_id is distinct from
       (select c.owner_id from public.classifieds c where c.id = m.listing_id);

-- وفهرسٌ للقراءة: المحادثةُ تُقرأ بـ(الإعلان، الطرف) مرتَّبةً بالوقت.
create index if not exists messages_thread_idx
  on public.messages (listing_id, buyer_id, created_at);

-- ---------------------------------------------------------------
-- 2) السياسة
-- ---------------------------------------------------------------
drop policy if exists "two parties: read" on public.messages;
create policy "two parties: read" on public.messages for select
  using (
    sender_id = auth.uid()
    or buyer_id = auth.uid()
    or auth.uid() = (select c.owner_id from public.classifieds c where c.id = listing_id)
    or public.is_admin()
  );

-- ⚠️ وسياسةُ الإدراج تكسب شرطاً، وهو نصفُ الإصلاح لا تجميل: العمودُ
-- الذي يوصّل الرسالةَ يفتح باباً لو تُرك بلا حارس — يضع صاحبُ الإعلان
-- `buyer_id` لأيّ حسابٍ في الدنيا فيُدرِج رسالةً في صندوقِ من لم يكلّمه.
-- قناةُ إزعاجٍ بسياسةٍ عليها، وهي الجملةُ المكتوبةُ في `0013` نفسِها عن
-- جدول الإشعارات.
--
-- ⚠️ والشرطُ لا يُكتَب استعلاماً فرعيّاً داخل السياسة، وهذا مقيسٌ لا
-- مقروء: `exists` على `public.messages` داخل سياسةٍ على
-- `public.messages` تستدعي حارسَ التكرار في PostgreSQL:
--     ERROR: infinite recursion detected in policy for relation "messages"
-- فيُرفَض كلُّ إدراجٍ من كلّ طرف — سوقٌ لا يستطيع أحدٌ فيه أن يرسل
-- رسالةً أصلاً، وهو أسوأُ من العطل الذي تصلحه هذه الهجرة. ولا سويتَ
-- بنيويّةً ترى ذلك: الملفُّ يُحلَّل بلا شكوى، والخادمُ البديلُ لا يطبّق
-- RLS. قاعدةٌ قائمة: الهجرةُ تُنفَّذ على PostgreSQL حقيقيّةٍ من الفراغ
-- قبل أن تُسمّى منتهية.
--
-- فالسؤالُ ينتقل إلى دالّةٍ بصلاحيّة مُعرِّفها، وهي الجوابُ المعروف
-- لتكرار السياسات.
--
-- ⚠️ ولا `security definer` — قِيست ولم تكن مطلوبة، والحجّةُ التي كادت
-- تُكتَب يكذّبها القياس. على قاعدتين متطابقتين، بالشكلين معاً:
--     الردُّ العاديّ   صفّان        صفّان
--     الهجومُ على غريب  صفر         صفر
--     مِسبارُ غريب       f            f
-- والسببُ أنّ الوحيدَ الذي يبلغ هذا الفرعَ أصلاً هو صاحبُ الإعلان، وهو
-- يقرأ رسائلَ إعلانه كلَّها بسياسة القراءة — فقراءةُ الدالّة بصلاحيّته
-- كاملةٌ ولا ينقصها شيء. وصلاحيّةٌ لا يحتاجها البناءُ لا تُمنَح، وهي
-- قاعدةُ `0005` مقروءةً بالعكس. وهذا هو خطأُ `0014` بعينِه: سببٌ
-- يُكتَب في هجرةٍ يُقاس أو لا يُكتَب.
--
-- ⚠️ ولا تثبيتَ لـ`search_path` لهذا السبب نفسِه: تثبيتُه يحرس دالّةً
-- تعمل بصلاحيّة مُعرِّفها، وهذه ليست كذلك — وكلُّ اسمٍ فيها مُسمّى
-- بمخطَّطه.
--
-- ⚠️ وهي تحمل شرطَ الملكيّة داخلَها ولا تجيب عن «هل بينهما محادثة»
-- مجرّدةً: لو أجابت لصارت مِسباراً يعرف به أيُّ أحدٍ أنّ فلاناً كلّم
-- إعلانَ فلان. وبالشرط داخلَها لا تجيب إلّا صاحبَ الإعلان — وهو يقرأ
-- رسائلَ إعلانه كلَّها أصلاً، فلا تخبره بشيءٍ يعجز عنه. مقيس: غريبٌ
-- يسأل عن محادثةٍ قائمةٍ فيأتيه `f`.
--
-- ⚠️ وأسماءُ الوسائط `p_listing` و`p_buyer` لا تُسمّى بأسماء الأعمدة،
-- وهذه سنٌّ عضّت: الاسمُ العاري داخل الجسم يرتبط بالوسيط أوّلاً فيصير
-- الشرطُ صحيحاً دائماً. قِيس بالتسميتين، والفرقُ حرفان: بالأسماء
-- العارية نزلت رسالةُ الهجوم في صندوق الغريب — صفٌّ واحد — وبالوسائط
-- المسمّاة صفر.
create or replace function public.can_reply_in_thread(p_listing uuid, p_buyer uuid)
returns boolean
language sql
stable
as $fn$
  select exists (select 1 from public.classifieds c
                  where c.id = p_listing and c.owner_id = auth.uid())
     and exists (select 1 from public.messages m
                  where m.listing_id = p_listing and m.buyer_id = p_buyer)
$fn$;

drop policy if exists "sender: insert" on public.messages;
create policy "sender: insert" on public.messages for insert
  with check (
    sender_id = auth.uid()
    and (
      -- المشتري: مفتاحُ المحادثة هو نفسُه، ولا يستطيع سواه
      (buyer_id = auth.uid()
       and auth.uid() is distinct from
           (select c.owner_id from public.classifieds c where c.id = listing_id))
      or
      -- صاحبُ الإعلان: يردّ في محادثةٍ قائمة، ولا يفتح واحدةً على غريب
      public.can_reply_in_thread(listing_id, buyer_id)
    )
  );

-- ⚠️ ولا تُفتَح سياسةُ تعديلٍ ولا حذف، لأحد. القرارُ المكتوب في `0001`
-- و`0002` قائم: رسالةٌ تُعدَّل بعد أن تُقرأ ليست سجلّاً، والبلاغُ يستند
-- إليها.

-- ---------------------------------------------------------------
-- 3) واسمُ الطرف الآخر
-- ---------------------------------------------------------------
-- ⚠️ وقائمةُ المحادثات تسمّي الطرفَ الآخر، وإلّا فبائعٌ عليه ثلاثةُ
-- سائلين يرى ثلاثةَ سطورٍ متطابقة: العنوانُ نفسُه ثلاثَ مرّات. وهو ما
-- تمنعه هذه الهجرةُ في البيانات ثمّ تعيده على الشاشة.
--
-- ⚠️ ولا تُوسَّع سياسةُ `profiles` لأجل ذلك. قِيست وهي `id = auth.uid()`
-- أو الإدارة — فالبائعُ لا يقرأ اسمَ المشتري أصلاً — وفتحُها لكلّ حسابٍ
-- مسجَّلٍ ينشر أسماءَ الناس كلِّهم وتفضيلاتِهم وعلامةَ الإدارة معها،
-- ثمناً لسطرٍ في قائمة. وسياسةٌ لا تُضعَّف لأجل راحةِ عرضٍ.
--
-- ⚠️ وهنا `security definer` مطلوبةٌ فعلاً، بخلاف الدالّة فوق، والفرقُ
-- مقيسٌ لا مقروء: تلك تقرأ جدولاً يقرؤه المنادي أصلاً، وهذه تقرأ صفّاً
-- لا يبلغه بحال. فالكلمةُ نفسُها تُرفَض في موضعٍ وتُطلَب في آخر، وكلا
-- الحكمين بقياس.
--
-- ولا تجيب إلّا طرفاً في محادثةٍ قائمة، وبالاسم وحدَه:
--   المشتري يسأل  ->  اسمُ صاحبِ الإعلان
--   صاحبُ الإعلان ->  اسمُ المشتري، ولمحادثةٍ قائمةٍ فقط
--   أيُّ أحدٍ سواهما -> لا شيء
-- وليس فيها تسريبٌ فوق ما تكشفه المحادثةُ نفسُها: من كتب إليك اختار أن
-- يكتب، ومن نشر إعلاناً اختار أن ينشره.
create or replace function public.thread_party_name(p_listing uuid, p_buyer uuid)
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $fn$
  select p.display_name
    from public.profiles p
   where p.id = case when auth.uid() = p_buyer
                     then (select c.owner_id from public.classifieds c where c.id = p_listing)
                     else p_buyer end
     and (auth.uid() = p_buyer
          or exists (select 1 from public.classifieds c
                      where c.id = p_listing and c.owner_id = auth.uid()))
     and exists (select 1 from public.messages m
                  where m.listing_id = p_listing and m.buyer_id = p_buyer)
$fn$;

revoke all on function public.thread_party_name(uuid, uuid) from public;
grant execute on function public.thread_party_name(uuid, uuid) to authenticated;
