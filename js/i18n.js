let currentLang = 'ar';

export function setLang(l) {
  currentLang = l === 'en' ? 'en' : 'ar';
  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
}
export function getLang() { return currentLang; }
export function t(key) {
  const pack = STRINGS[currentLang] || STRINGS.ar;
  return pack[key] !== undefined ? pack[key] : (STRINGS.ar[key] !== undefined ? STRINGS.ar[key] : key);
}
/** Both packs, for anything that must match in either language regardless
    of the interface setting — the directory search, for one. */
export function bothPacks() { return STRINGS; }

/** pick a localized field from a data object: {ar:'..', en:'..'} */
export function L(obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  // An empty side falls back to the other one. Most shops here trade under an
  // English name only, and a blank name in the Arabic interface would be worse
  // than showing the name written on the shopfront.
  return obj[currentLang] || obj.ar || obj.en || '';
}
