/* ------------------------------------------------------------
   THE COUNTED NOUN

   Arabic has four cases where English has two, and the app knew
   only one of them: singular, and everything-else-is-plural. So
   the countdown under the header read «باقي 2 ساعات» for two
   hours and «باقي 12 ساعات» for twelve — and it repaints every
   minute on the first screen anybody sees.

     1     singular, no number    ساعة
     2     DUAL                   ساعتان
     3–10  number + plural        3 ساعات
     11+   number + SINGULAR      11 ساعة

   English fills all four slots with its two forms, so there is
   one function and no `if (lang)` anywhere.
   ------------------------------------------------------------ */
export function arCount(n, forms) {
  const f = Array.isArray(forms) ? forms : [forms, forms, forms, forms];
  if (n === 1) return f[0];
  if (n === 2) return f[1];
  if (n >= 3 && n <= 10) return `${n} ${f[2]}`;
  return `${n} ${f[3]}`;
}

/** pick a localized field from a data object: {ar:'..', en:'..'} */
export function L(obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  // An empty side falls back to the other one. Most shops here trade under an
  // English name only, and a blank name in the Arabic interface would be worse
  // than showing the name written on the shopfront.
  return obj[currentLang] || obj.ar || obj.en || '';
}
